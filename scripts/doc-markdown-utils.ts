export function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function safeDecodeURIComponent(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

export function parseTsSourceFile(
  filePath: string,
  content: string,
  setParentNodes = false
): ts.SourceFile {
  const kind =
    filePath.endsWith('.tsx') || filePath.endsWith('.jsx')
      ? ts.ScriptKind.TSX
      : ts.ScriptKind.TS;
  return ts.createSourceFile(filePath, content, ts.ScriptTarget.Latest, setParentNodes, kind);
}

export function getTsPropertyKeyName(nameNode: ts.PropertyName): string | null {
  if (
    ts.isIdentifier(nameNode) ||
    ts.isStringLiteral(nameNode) ||
    ts.isNoSubstitutionTemplateLiteral(nameNode)
  ) {
    return nameNode.text;
  }
  return null;
}

export function findInlineCodeEnd(
  line: string,
  start: number
): { tickLen: number; closeEnd: number | null } {
  let tickLen = 0;
  while (start + tickLen < line.length && line[start + tickLen] === '`') {
    tickLen++;
  }
  const ticks = '`'.repeat(tickLen);
  let searchFrom = start + tickLen;

  while (searchFrom < line.length) {
    const idx = line.indexOf(ticks, searchFrom);
    if (idx === -1) break;
    const beforeOk = idx === 0 || line[idx - 1] !== '`';
    const afterOk = idx + tickLen >= line.length || line[idx + tickLen] !== '`';
    if (beforeOk && afterOk) {
      return { tickLen, closeEnd: idx + tickLen };
    }
    searchFrom = idx + 1;
  }

  return { tickLen, closeEnd: null };
}

function normalizeLinkDestination(rawInner: string): string {
  const trimmed = rawInner.trim();
  if (trimmed.startsWith('<')) {
    const closeAngle = trimmed.indexOf('>');
    if (closeAngle !== -1) return trimmed.slice(1, closeAngle).trim();
  }
  const titleMatch = trimmed.match(/^(\S+)\s+(?:"[^"]*"|'[^']*')$/);
  return titleMatch ? titleMatch[1] : trimmed;
}

export function scanLinksAndCodeInLine(
  line: string,
  lineNumber: number = 1
): { links: ParsedMarkdownLink[]; codeSpans: InlineCodeSpan[] } {
  const links: ParsedMarkdownLink[] = [];
  const codeSpans: InlineCodeSpan[] = [];

  let i = 0;
  while (i < line.length) {
    if (line[i] === '\\') {
      i += 2;
      continue;
    }

    if (line[i] === '`') {
      const { tickLen, closeEnd } = findInlineCodeEnd(line, i);
      if (closeEnd !== null) {
        codeSpans.push({
          text: line.slice(i + tickLen, closeEnd - tickLen),
          startIndex: i,
          endIndex: closeEnd,
        });
        i = closeEnd;
      } else {
        i += tickLen;
      }
      continue;
    }

    if (line[i] === '[') {
      let bracketDepth = 1;
      let j = i + 1;
      const innerCodeSpans: InlineCodeSpan[] = [];

      while (j < line.length && bracketDepth > 0) {
        if (line[j] === '\\') {
          j += 2;
          continue;
        }
        if (line[j] === '`') {
          const { tickLen, closeEnd } = findInlineCodeEnd(line, j);
          if (closeEnd !== null) {
            innerCodeSpans.push({
              text: line.slice(j + tickLen, closeEnd - tickLen),
              startIndex: j,
              endIndex: closeEnd,
            });
            j = closeEnd;
          } else {
            j += tickLen;
          }
          continue;
        }
        if (line[j] === '[') bracketDepth++;
        else if (line[j] === ']') bracketDepth--;
        j++;
      }

      if (bracketDepth === 0 && j < line.length && line[j] === '(') {
        let k = j + 1;
        let parenDepth = 1;
        let firstNonSpace = k;
        while (firstNonSpace < line.length && /\s/.test(line[firstNonSpace])) {
          firstNonSpace++;
        }
        let inAngleBrackets = line[firstNonSpace] === '<';

        while (k < line.length && parenDepth > 0) {
          if (line[k] === '\\') {
            k += 2;
            continue;
          }
          if (inAngleBrackets && line[k] === '>') {
            inAngleBrackets = false;
            k++;
            continue;
          }
          if (!inAngleBrackets) {
            if (line[k] === '(') parenDepth++;
            else if (line[k] === ')') parenDepth--;
          }
          k++;
        }

        if (parenDepth === 0) {
          const isImage = i > 0 && line[i - 1] === '!' && (i < 2 || line[i - 2] !== '\\');
          links.push({
            line: lineNumber,
            startIndex: i,
            endIndex: k,
            linkText: line.slice(i + 1, j - 1),
            rawTarget: normalizeLinkDestination(line.slice(j + 1, k - 1)),
            isImage,
          });
          codeSpans.push(...innerCodeSpans);
          i = k;
          continue;
        }
      }
    }

    i++;
  }

  return { links, codeSpans };
}

export function parseLineFragmentRange(
  fragment: string
): { start: number; end: number } | null {
  const normalized = fragment.startsWith('#') ? fragment.slice(1) : fragment;
  const match = normalized.match(LINE_FRAGMENT_RE);
  if (!match) return null;
  const start = parseInt(match[1], 10);
  const end = match[2] !== undefined ? parseInt(match[2], 10) : start;
  return { start, end };
}

export function extractFilePathFromLinkTarget(
  rawTarget: string,
  fileDir: string,
  rootDir: string,
  options?: ExtractFilePathOptions
): string | null {
  const trimmed = rawTarget.trim();
  const repoMatch = trimmed.match(REPO_GITHUB_URL_RE);
  if (repoMatch) {
    if (repoMatch[1] === 'tree') return null;
    const repoRel = safeDecodeURIComponent(repoMatch[2]).replace(/\/+$/, '');
    return repoRel ? path.resolve(rootDir, repoRel) : null;
  }

  if (
    trimmed.startsWith('http://') ||
    trimmed.startsWith('https://') ||
    trimmed.startsWith('mailto:') ||
    trimmed.startsWith('tel:') ||
    trimmed.startsWith('#')
  ) {
    return null;
  }

  const cleanPath = safeDecodeURIComponent(trimmed.split('#')[0].split('?')[0].trim());
  if (!cleanPath) return null;
  if (cleanPath.startsWith('/')) return path.resolve(rootDir, cleanPath.slice(1));

  if (options?.resolveRepoRootSrc) {
    if (cleanPath.startsWith('src/')) return path.resolve(rootDir, cleanPath);
    if (!cleanPath.startsWith('./') && !cleanPath.startsWith('../')) return null;
  }

  return path.resolve(fileDir, cleanPath);
}

export function stripHtmlTags(input: string): string {
  let result = '';
  let depth = 0;
  let quote: '"' | "'" | null = null;

  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (depth > 0) {
      if (quote !== null) {
        if (ch === quote) quote = null;
        continue;
      }
      if (ch === '"' || ch === "'") {
        const closeQuote = input.indexOf(ch, i + 1);
        if (closeQuote !== -1 && input.indexOf('>', closeQuote + 1) !== -1) {
          quote = ch;
        }
        continue;
      }
      if (ch === '<') depth++;
      else if (ch === '>') depth--;
      continue;
    }

    if (ch === '<') {
      depth = 1;
      continue;
    }
    if (ch !== '>') result += ch;
  }

  return result;
}

export function stripInlineMarkdown(raw: string): string {
  let s = raw;
  let prev = '';
  while (s !== prev) {
    prev = s;
    const { links } = scanLinksAndCodeInLine(s, 1);
    if (links.length === 0) break;
    let rebuilt = '';
    let cursor = 0;
    for (const link of links) {
      const prefixEnd = link.isImage ? link.startIndex - 1 : link.startIndex;
      rebuilt += s.slice(cursor, prefixEnd) + link.linkText;
      cursor = link.endIndex;
    }
    s = rebuilt + s.slice(cursor);
  }

  let tokenPrefix = '\uE000CODE';
  while (s.includes(tokenPrefix)) tokenPrefix += '_';
  const codeContents: string[] = [];
  let tokenized = '';
  let idx = 0;
  while (idx < s.length) {
    if (s[idx] === '`') {
      const { tickLen, closeEnd } = findInlineCodeEnd(s, idx);
      if (closeEnd !== null) {
        codeContents.push(s.slice(idx + tickLen, closeEnd - tickLen));
        tokenized += `${tokenPrefix}${codeContents.length - 1}\uE001`;
        idx = closeEnd;
        continue;
      }
      tokenized += s.slice(idx, idx + tickLen);
      idx += tickLen;
      continue;
    }
    tokenized += s[idx];
    idx++;
  }
  s = stripHtmlTags(
    tokenized
      .replace(/(\*\*|__)(.*?)\1/g, '$2')
      .replace(/(\*|_)(?=\S)(.+?)(?<=\S)\1/g, '$2')
      .replace(/~~(.*?)~~/g, '$1')
      .replace(/\\([\\`*_{}[\]()#+\-.!|])/g, '$1')
  );

  for (let c = 0; c < codeContents.length; c++) {
    s = s.split(`${tokenPrefix}${c}\uE001`).join(codeContents[c]);
  }
  return s.trim();
}

export function vitepressSlugify(str: string): string {
  return str
    .normalize('NFKD')
    .replace(VP_COMBINING_RE, '')
    .replace(VP_CONTROL_RE, '')
    .replace(VP_SPECIAL_RE, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/^(\d)/, '_$1')
    .toLowerCase();
}

export function githubSlugify(str: string): string {
  return str
    .trim()
    .toLowerCase()
    .replace(/[\uFE00-\uFE0F\u200D]/g, '')
    .replace(/[^\p{L}\p{M}\p{N}_\- ]/gu, '')
    .replace(/ /g, '-');
}

export function stepMarkdownFence(
  rawLine: string,
  state: MarkdownFenceState
): FenceTransitionResult {
  const fenceMatch = rawLine.match(COMMONMARK_FENCE_RE);
  if (fenceMatch) {
    const marker = fenceMatch[1];
    const rest = fenceMatch[2];
    const ch = marker[0];
    const len = marker.length;
    if (!state.inFence) {
      if (!(ch === '`' && rest.includes('`'))) {
        state.inFence = true;
        state.fenceChar = ch;
        state.fenceLen = len;
        return { kind: 'open', infoString: rest };
      }
    } else if (ch === state.fenceChar && len >= state.fenceLen && /^\s*$/.test(rest)) {
      state.inFence = false;
      state.fenceChar = '';
      state.fenceLen = 0;
      return { kind: 'close' };
    }
  }

  return state.inFence ? { kind: 'inside' } : { kind: 'outside' };
}

export function scanMarkdownDocument(
  content: string,
  onLine: (_line: string, _lineNumber: number) => void,
  options: MarkdownScanOptions = {}
): void {
  const frontmatterMode = options.frontmatterMode ?? 'none';
  const htmlCommentMode = options.htmlCommentMode ?? 'none';
  const skipAutogen = Boolean(options.skipAutogeneratedBlocks);

  const lines = content.split(/\r?\n/);
  const fenceState: MarkdownFenceState = { inFence: false, fenceChar: '', fenceLen: 0 };
  const skippedAutogenFence: MarkdownFenceState = { inFence: false, fenceChar: '', fenceLen: 0 };

  let inFrontmatter = false;
  const frontmatterLines: string[] = [];
  let inMermaidFence = false;
  let mermaidFenceStartLine = 0;
  let mermaidLines: string[] = [];
  let inHtmlComment = false;
  let inSkippedAutogenBlock = false;

  lines.forEach((rawLine, index) => {
    const lineNum = index + 1;

    if (frontmatterMode !== 'none') {
      if (index === 0 && rawLine.trim() === '---') {
        inFrontmatter = true;
        return;
      }
      if (inFrontmatter) {
        if (rawLine.trim() === '---' || rawLine.trim() === '...') {
          inFrontmatter = false;
          if (frontmatterMode === 'collect') options.onFrontmatter?.(frontmatterLines);
        } else if (frontmatterMode === 'collect') {
          frontmatterLines.push(rawLine);
        }
        return;
      }
    }

    if (inSkippedAutogenBlock) {
      if (
        stepMarkdownFence(rawLine, skippedAutogenFence).kind === 'outside' &&
        AUTOGEN_END_RE.test(rawLine.trim())
      ) {
        inSkippedAutogenBlock = false;
      }
      return;
    }

    const fenceStep = stepMarkdownFence(rawLine, fenceState);
    if (fenceStep.kind === 'open') {
      const markerMatch = rawLine.match(COMMONMARK_FENCE_RE);
      options.onFenceOpen?.(fenceStep.infoString, markerMatch ? markerMatch[1] : '```', lineNum);
      if (options.onMermaidBlock) {
        const infoLang = fenceStep.infoString.trim().split(/[\s{[:]/)[0]?.toLowerCase() ?? '';
        if (infoLang === 'mermaid' || infoLang === 'mmd') {
          inMermaidFence = true;
          mermaidFenceStartLine = lineNum;
          mermaidLines = [];
        }
      }
      options.onFenceBoundary?.();
      return;
    }
    if (fenceStep.kind === 'close') {
      if (inMermaidFence) {
        options.onMermaidBlock?.({
          fenceStartLine: mermaidFenceStartLine,
          code: mermaidLines.join('\n'),
        });
        inMermaidFence = false;
        mermaidFenceStartLine = 0;
        mermaidLines = [];
      }
      options.onFenceBoundary?.();
      return;
    }
    if (fenceStep.kind === 'inside') {
      if (inMermaidFence) mermaidLines.push(rawLine);
      return;
    }

    if (skipAutogen && !inHtmlComment) {
      const trimmed = rawLine.trim();
      const beginMatch = trimmed.match(AUTOGEN_BEGIN_RE);
      if (beginMatch) {
        const blockName = beginMatch[1] ?? '';
        inSkippedAutogenBlock = !(blockName && options.includedAutogenBlocks?.has(blockName));
        skippedAutogenFence.inFence = false;
        skippedAutogenFence.fenceChar = '';
        skippedAutogenFence.fenceLen = 0;
        return;
      }
      if (AUTOGEN_END_RE.test(trimmed)) return;
    }

    let lineText = rawLine;
    let hadComment = false;
    if (htmlCommentMode !== 'none') {
      let pos = 0;
      if (inHtmlComment) {
        const endIdx = lineText.indexOf('-->');
        if (endIdx === -1) return;
        hadComment = true;
        inHtmlComment = false;
        if (htmlCommentMode === 'pad') {
          lineText = ' '.repeat(endIdx + 3) + lineText.slice(endIdx + 3);
          pos = endIdx + 3;
        } else {
          lineText = lineText.slice(endIdx + 3);
          pos = 0;
        }
      }

      while (pos < lineText.length) {
        if (lineText[pos] === '\\') {
          pos += 2;
          continue;
        }
        if (lineText[pos] === '`') {
          const { tickLen, closeEnd } = findInlineCodeEnd(lineText, pos);
          pos = closeEnd !== null ? closeEnd : pos + tickLen;
          continue;
        }
        if (lineText.startsWith('<!--', pos)) {
          hadComment = true;
          const endIdx = lineText.indexOf('-->', pos + 4);
          if (endIdx === -1) {
            lineText = lineText.slice(0, pos);
            inHtmlComment = true;
            break;
          }
          if (htmlCommentMode === 'pad') {
            const padLen = endIdx + 3 - pos;
            lineText = lineText.slice(0, pos) + ' '.repeat(padLen) + lineText.slice(endIdx + 3);
            pos += padLen;
          } else {
            lineText = lineText.slice(0, pos) + lineText.slice(endIdx + 3);
          }
          continue;
        }
        pos++;
      }

      if (htmlCommentMode === 'strip' && hadComment && lineText.trim() === '') return;
    }

    onLine(lineText, lineNum);
  });

  if (inMermaidFence) {
    options.onMermaidBlock?.({
      fenceStartLine: mermaidFenceStartLine,
      code: mermaidLines.join('\n'),
    });
  }
}

export function transformNonFencedMarkdownLines(
  content: string,
  transformLine: (_line: string, _lineNumber: number) => string
): string {
  const chunks = content.match(/[^\r\n]*(?:\r?\n|$)/g) || [];
  const fenceState: MarkdownFenceState = { inFence: false, fenceChar: '', fenceLen: 0 };

  return chunks
    .map((chunk, idx) => {
      if (!chunk) return '';
      const lineMatch = chunk.match(/^([^\r\n]*)(\r?\n?)$/);
      const line = lineMatch ? lineMatch[1] : chunk;
      const eol = lineMatch ? lineMatch[2] : '';
      if (stepMarkdownFence(line, fenceState).kind !== 'outside') return chunk;
      return transformLine(line, idx + 1) + eol;
    })
    .join('');
}

export function extractMarkdownHeadings(content: string): MarkdownHeading[] {
  const headings: MarkdownHeading[] = [];
  const vpCounts = new Map<string, number>();
  const ghCounts = new Map<string, number>();

  scanMarkdownDocument(
    content,
    (line, lineNum) => {
      const headingMatch = line.match(/^\s{0,3}(#{1,6})\s+(.+?)(?:\s+#+\s*)?$/);
      if (!headingMatch) return;

      const level = headingMatch[1].length;
      const headingRaw = headingMatch[2].trim();
      const customIdMatch = headingRaw.match(/\s*\{#([^}]+)\}\s*$/);

      let baseVp: string;
      let baseGh: string;
      if (customIdMatch) {
        baseVp = customIdMatch[1];
        baseGh = customIdMatch[1];
      } else {
        const plain = stripInlineMarkdown(headingRaw);
        baseVp = vitepressSlugify(plain);
        baseGh = githubSlugify(plain);
      }

      const vpSeen = vpCounts.get(baseVp) || 0;
      vpCounts.set(baseVp, vpSeen + 1);
      const ghSeen = ghCounts.get(baseGh) || 0;
      ghCounts.set(baseGh, ghSeen + 1);

      headings.push({
        line: lineNum,
        level,
        rawText: headingRaw,
        githubSlug: ghSeen === 0 ? baseGh : `${baseGh}-${ghSeen}`,
        vitepressSlug: vpSeen === 0 ? baseVp : `${baseVp}-${vpSeen}`,
      });
    },
    { frontmatterMode: 'skip', htmlCommentMode: 'strip' }
  );

  return headings;
}

export function resolveVitePressHeadingSlug(
  targetMarkdownPath: string,
  rawHash: string,
  headingsCache?: Map<string, MarkdownHeading[]>
): string {
  if (!rawHash || LINE_FRAGMENT_RE.test(rawHash)) return rawHash;

  let headings = headingsCache?.get(targetMarkdownPath);
  if (!headings) {
    try {
      headings = extractMarkdownHeadings(fs.readFileSync(targetMarkdownPath, 'utf8'));
      headingsCache?.set(targetMarkdownPath, headings);
    } catch {
      return rawHash;
    }
  }

  const decoded = safeDecodeURIComponent(rawHash);
  const directVp = headings.find(h => h.vitepressSlug === decoded);
  if (directVp) return directVp.vitepressSlug;
  const fromGh = headings.find(h => h.githubSlug === decoded);
  return fromGh ? fromGh.vitepressSlug : rawHash;
}

export function buildTsDeclRanges(
  filePath: string,
  content: string,
  sourceFile?: ts.SourceFile
): Map<string, TsDeclRange[]> {
  const declRanges = new Map<string, TsDeclRange[]>();
  if (!/\.[cm]?[jt]sx?$/.test(filePath)) return declRanges;

  const sf = sourceFile ?? parseTsSourceFile(filePath, content, false);
  const lineStarts = sf.getLineStarts();
  const offsetToLine = (pos: number): number => {
    let low = 0;
    let high = lineStarts.length - 1;
    while (low <= high) {
      const mid = (low + high) >>> 1;
      if (lineStarts[mid] <= pos) low = mid + 1;
      else high = mid - 1;
    }
    return high + 1;
  };
  const skipTrivia = (pos: number, end: number): number => {
    let p = pos;
    while (p < end) {
      const ch = content.charCodeAt(p);
      if (ch === 32 || ch === 9 || ch === 10 || ch === 13) p++;
      else if (ch === 47 && content.charCodeAt(p + 1) === 47) {
        p += 2;
        while (p < end && content.charCodeAt(p) !== 10) p++;
      } else if (ch === 47 && content.charCodeAt(p + 1) === 42) {
        p += 2;
        while (p + 1 < end && !(content.charCodeAt(p) === 42 && content.charCodeAt(p + 1) === 47)) {
          p++;
        }
        p += 2;
      } else {
        break;
      }
    }
    return p;
  };
  const addRange = (name: string, node: ts.Node) => {
    const start = offsetToLine(skipTrivia(node.pos, node.end));
    const end = offsetToLine(Math.max(node.pos, node.end - 1));
    const arr = declRanges.get(name) ?? [];
    arr.push({ start, end });
    declRanges.set(name, arr);
  };
  const visit = (node: ts.Node) => {
    if (
      (ts.isFunctionDeclaration(node) ||
        ts.isClassDeclaration(node) ||
        ts.isInterfaceDeclaration(node) ||
        ts.isTypeAliasDeclaration(node) ||
        ts.isEnumDeclaration(node)) &&
      node.name
    ) {
      addRange(node.name.text, node);
    } else if (ts.isVariableStatement(node)) {
      for (const decl of node.declarationList.declarations) {
        if (ts.isIdentifier(decl.name)) addRange(decl.name.text, node);
      }
    } else if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
      addRange(node.name.text, node);
    } else if (
      (ts.isMethodDeclaration(node) ||
        ts.isPropertyDeclaration(node) ||
        ts.isPropertySignature(node) ||
        ts.isMethodSignature(node) ||
        ts.isGetAccessorDeclaration(node) ||
        ts.isSetAccessorDeclaration(node) ||
        ts.isPropertyAssignment(node) ||
        ts.isShorthandPropertyAssignment(node)) &&
      node.name &&
      (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name))
    ) {
      addRange(node.name.text, node);
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
  return declRanges;
}
