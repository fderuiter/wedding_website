export const REPO_GITHUB_URL_RE =
  /^https?:\/\/github\.com\/fderuiter\/wedding_website\/(blob|tree)\/[^/]+\/([^?#]*)(?:\?[^#]*)?(?:#(.*))?$/;
export const LINE_FRAGMENT_RE = /^L(\d+)(?:C\d+)?(?:-L?(\d+)(?:C\d+)?)?$/;

export const PROSE_LINK_WORDS = new Set([
  'details', 'docs', 'example', 'file', 'handler', 'here', 'implementation', 'link',
  'module', 'more', 'repo', 'route', 'sample', 'schema', 'service', 'source', 'target',
]);

export const HTTP_METHOD_NAMES = new Set([
  'GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS',
]);

const VP_CONTROL_RE = /[\u0000-\u001f]/g;
const VP_SPECIAL_RE = /[\s~`!@#$%^&*()\-_+=[\]{}|\\;:"'\u201C\u201D\u2018\u2019<>,.?/]+/g;
const VP_COMBINING_RE = /[\u0300-\u036F]/g;
const COMMONMARK_FENCE_RE = /^\s{0,3}(`{3,}|~{3,})(.*)$/;
const AUTOGEN_BEGIN_RE = /^<!--\s*BEGIN\s+AUTOGENERATED(?:\s+([A-Z0-9_]+))?\s*-->$/;
const AUTOGEN_END_RE = /^<!--\s*END\s+AUTOGENERATED(?:\s+[A-Z0-9_]+)?\s*-->$/;

